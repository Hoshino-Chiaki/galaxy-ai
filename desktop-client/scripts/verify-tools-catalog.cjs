const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { chromium } = require('../../session_research/runtime/node_modules/playwright-core')

;(async () => {
  let browser
  for (let n=0; n<15; n++) {
    try { browser = await chromium.connectOverCDP('http://127.0.0.1:19224'); break }
    catch { await new Promise(resolve => setTimeout(resolve, 400)) }
  }
  assert(browser)
  const page = browser.contexts()[0].pages().find(p => p.url().includes('index.html'))
  assert(page)
  const errors = []
  page.on('pageerror', () => errors.push('renderer error'))
  try {
    await page.waitForFunction(() => !!document.querySelector('.workspace-page') || !!(document.querySelector('#account') && !document.querySelector('#account').disabled))
    if (await page.locator('#account').count()) {
      const lines = fs.readFileSync(path.resolve(__dirname, '../../1.txt'), 'utf8').replace(/^\uFEFF/, '').split(/\r?\n/)
      await page.locator('#account').fill(lines[0]); await page.locator('#password').fill(lines[1])
      await page.getByRole('checkbox', { name: '记住登录' }).check({ force: true })
      await page.locator('.login-button').click()
      await page.locator('.workspace-page').waitFor()
    }
    const navigation = page.getByRole('button', { name: '控制台', exact: true })
    if (await navigation.getAttribute('aria-expanded') !== 'true') await navigation.click()
    await page.getByRole('button', { name: '控制台 AI', exact: true }).click()
    assert.deepEqual(await page.locator('.console-tabs [role=tab]').allTextContents(), ['AI 模型', '全局提示词', '工具列表'])
    await page.getByRole('tab', { name: '工具列表', exact: true }).click()
    await page.getByRole('button', { name: '刷新', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('.tools-toolbar button').disabled)
    await page.locator('.tool-card').first().waitFor()
    const catalogResponse = await page.evaluate(() => window.desktop.service.request('admin.tools'))
    assert.equal(catalogResponse.ok, true)
    const catalog = catalogResponse.data
    assert.equal(typeof catalog.version, 'string')
    assert.equal(catalog.data.length, 5)
    for (const tool of catalog.data) assert.deepEqual(Object.keys(tool), ['tool', 'category', 'description'])
    assert.deepEqual(new Set(catalog.data.map(t => t.tool)), new Set(['file.publish', 'excel.create', 'youzan.customer-search', 'youzan.customer-get', 'youzan.business-report']))
    await page.getByRole('tab', { name: 'youzan', exact: true }).click()
    assert.equal(await page.locator('.tool-card').count(), 3)
    const geometry = await page.evaluate(() => {
      const side = document.querySelector('.tools-sidebar').getBoundingClientRect()
      const content = document.querySelector('.tools-content').getBoundingClientRect()
      const cards = [...document.querySelectorAll('.tool-card')].map(e => e.getBoundingClientRect())
      return { sidebarLeft: side.right < content.left, compactCards: cards.every(r => r.height <= 130), sidebarWidth: side.width, cardHeight: Math.round(cards[0].height) }
    })
    assert(geometry.sidebarLeft && geometry.compactCards)
    assert.equal(await page.getByRole('tablist', { name: '工具分类', exact: true }).getAttribute('aria-orientation'), 'vertical')
    assert.equal(await page.locator('.tool-help-output').count(), 0)
    assert.equal(await page.locator('#tool-description-panel').count(), 0)
    const dir = path.resolve(__dirname, '../artifacts')
    await page.screenshot({ path: path.join(dir, 'windows-tools-cards.png') })
    const reportCard = page.getByRole('button', { name: 'youzan.business-report 查看描述', exact: true })
    await reportCard.click()
    assert.equal(await page.locator('#tool-description-panel > p').innerText(), catalog.data.find(t => t.tool === 'youzan.business-report').description)
    assert((await page.locator('#tool-description-panel > p').innerText()).includes('business-report options'))
    assert((await page.locator('#tool-description-panel > p').innerText()).includes('business-report query'))
    await page.screenshot({ path: path.join(dir, 'windows-report-tool.png') })
    await page.getByRole('button', { name: '关闭工具描述', exact: true }).click()
    const getCard = page.getByRole('button', { name: 'youzan.customer-get 查看描述', exact: true })
    await getCard.click()
    const details = page.locator('#tool-description-panel > p')
    assert.equal(await details.innerText(), catalog.data.find(t => t.tool === 'youzan.customer-get').description)
    assert.equal(await getCard.getAttribute('aria-expanded'), 'true')
    assert((await details.innerText()).includes('account_type'))
    await page.getByRole('button', { name: '刷新', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('.tools-toolbar button').disabled)
    assert.equal(await getCard.getAttribute('aria-expanded'), 'true')
    await page.screenshot({ path: path.join(dir, 'windows-tools-description.png') })
    await page.getByRole('button', { name: '关闭工具描述', exact: true }).click()
    assert.equal(await getCard.evaluate(e => e === document.activeElement), true)
    const searchCard = page.getByRole('button', { name: 'youzan.customer-search 查看描述', exact: true })
    await searchCard.click()
    assert.equal(await details.innerText(), catalog.data.find(t => t.tool === 'youzan.customer-search').description)
    await page.getByRole('tab', { name: '工具列表', exact: true }).focus()
    await page.keyboard.press('ArrowLeft')
    assert.equal(await page.getByRole('tab', { name: '全局提示词', exact: true }).getAttribute('aria-selected'), 'true')
    await page.keyboard.press('ArrowRight')
    await page.locator('.tool-card').first().waitFor()
    await page.getByRole('tab', { name: 'excel', exact: true }).click()
    assert.equal(await page.locator('.tool-card').count(), 1)
    await page.getByRole('button', { name: 'excel.create 查看描述', exact: true }).click()
    assert.equal(await page.locator('#tool-description-panel > p').innerText(), catalog.data.find(t => t.tool === 'excel.create').description)
    assert(!catalog.data.some(t => /HAR|抓包/.test(t.description)))
    await page.screenshot({ path: path.join(dir, 'windows-excel-tool.png') })
    await page.getByRole('button', { name: '关闭工具描述', exact: true }).click()
    await page.getByRole('tab', { name: 'file', exact: true }).click()
    assert.equal(await page.locator('.tool-card').count(), 1)
    await page.getByRole('button', { name: 'file.publish 查看描述', exact: true }).click()
    assert.equal(await page.locator('#tool-description-panel > p').innerText(), catalog.data.find(t => t.tool === 'file.publish').description)
    await page.screenshot({ path: path.join(dir, 'windows-file-tool.png') })
    const overflow = await page.locator('.console-scroll').evaluate(e => e.scrollWidth > e.clientWidth + 1)
    assert.equal(overflow, false)
    assert.deepEqual(errors, [])
    const result = { passed: true, actualWindowsApp: true, tabs: ['AI 模型','全局提示词','工具列表'],
      categoriesFromHelp: true, categories: [...new Set(catalog.data.map(tool => tool.category))], toolCards: 5, youzanTools: 3, ...geometry,
      completeDescriptions: true, refreshPreservesSelection: true, keyboardNavigation: true,
      noHorizontalOverflow: true, rendererErrors: 0 }
    fs.writeFileSync(path.join(dir,'tools-catalog-ui-check.json'),JSON.stringify(result,null,2))
    console.log(JSON.stringify(result))
  } finally { await browser.close() }
})().catch(() => { console.error(JSON.stringify({passed:false,message:'Tool catalog UI check failed; inspect UI without printing credentials.'}));process.exitCode=1 })
