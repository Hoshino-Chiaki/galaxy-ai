const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { chromium } = require('../../session_research/runtime/node_modules/playwright-core')
;(async () => {
 const browser = await chromium.connectOverCDP('http://127.0.0.1:19224')
 const page = browser.contexts()[0].pages().find(page => page.url().includes('index.html'))
 const errors = []; page.on('pageerror', error => errors.push(error.message))
 try {
  await page.locator('.workspace-page').waitFor()
  if (!await page.getByRole('button', { name: '控制台 AI', exact: true }).isVisible()) await page.getByRole('button', { name: '控制台', exact: true }).click()
  else await page.getByRole('button', { name: '控制台 AI', exact: true }).click()
  await page.getByRole('tab', { name: '工具提示词', exact: true }).click()
  const editor = page.getByRole('textbox', { name: '分类提示词', exact: true })
  await editor.waitFor()
  assert((await editor.inputValue()).includes('shops="all"'))
  const categoryCount = await page.locator('.tools-categories button').count()
  assert(categoryCount >= 3)
  assert(await page.getByRole('button', { name: '保存', exact: true }).isDisabled())
  const dir = path.resolve(__dirname, '../artifacts')
  await page.screenshot({ path: path.join(dir, 'windows-tool-prompts.png') })
  await page.locator('.tools-categories button').filter({ hasText: 'file' }).click()
  assert.equal(await editor.inputValue(), '')
  await page.getByRole('button', { name: '控制台 有赞', exact: true }).click()
  await page.locator('.shop-session-row').first().waitFor()
  assert.equal(await page.locator('.shop-session-row').count(), 7)
  assert.equal(await page.locator('.shop-session-row .ready').count(), 6)
  await page.locator('.shop-session-list').scrollIntoViewIfNeeded()
  await page.screenshot({ path: path.join(dir, 'windows-shop-sessions.png') })
  await page.getByRole('button', { name: '控制台 AI', exact: true }).click()
  await page.getByRole('tab', { name: '工具提示词', exact: true }).click()
  await page.getByRole('textbox', { name: '分类提示词', exact: true }).waitFor()
  assert.deepEqual(errors, [])
  const result = { passed: true, actualWindowsApp: true, version: '0.5.0', categoryCount,
   readyShopSessions: 6, permissionDeniedShops: 1, blankCategoryHasNoPrompt: true, rendererErrors: 0, configurationWrites: 0 }
  fs.writeFileSync(path.join(dir, 'tool-prompts-windows-check.json'), JSON.stringify(result, null, 2))
  console.log(JSON.stringify(result))
 } finally { await browser.close() }
})().catch(error => { console.error(error.message); process.exitCode = 1 })
