// Real Windows Electron -> Arch HTTPS API test. Never prints credentials or tokens.
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { chromium } = require('../../session_research/runtime/node_modules/playwright-core')
const phase = process.argv[2] || 'remember'
const credentialLines = fs.readFileSync(path.resolve(__dirname, '../../1.txt'), 'utf8').replace(/^\uFEFF/, '').split(/\r?\n/)
while (credentialLines.length && credentialLines.at(-1) === '') credentialLines.pop()
const accounts = Array.from({ length: Math.floor(credentialLines.length / 2) }, (_, index) => ({ username: credentialLines[index * 2], password: credentialLines[index * 2 + 1] }))
const { username } = accounts[0]
const artifacts = path.resolve(__dirname, '../artifacts')
fs.mkdirSync(artifacts, { recursive: true })

async function aiWorkspace(page, index = 0) {
  await page.locator('.workspace-page').waitFor()
  assert.equal(await page.locator('video').count(), 0)
  assert.equal(await page.locator('.scene').count(), 0)
  assert.equal(await page.locator('.video-control').count(), 0)
  assert.equal(await page.locator('#welcome-heading').innerText(), `Hello ${accounts[index].username}.`)
  assert.equal(await page.getByRole('button', { name: 'AI', exact: true }).getAttribute('aria-current'), 'page')
  assert.equal(await page.locator('.user-avatar').count(), 1)
  assert.equal(await page.locator('#chat-message').count(), 1)
  const metadata = await page.evaluate(() => window.desktop.auth.current())
  assert.equal(metadata.ok, true)
  assert.equal(metadata.data.user.role, index === 0 ? 'admin' : 'employee')
  assert.equal('access_token' in metadata.data, false)
  assert.equal('password_hash' in metadata.data.user, false)
}

async function login(page, remember, index = 0) {
  await page.locator('#account').waitFor()
  await page.waitForFunction(() => !document.querySelector('#account').disabled)
  await page.locator('#account').fill(accounts[index].username)
  await page.locator('#password').fill(accounts[index].password)
  await page.getByRole('checkbox', { name: '记住登录' }).setChecked(remember, { force: true })
  await page.locator('#password').press('Enter')
  await aiWorkspace(page, index)
}

async function logout(page) {
  await page.getByRole('button', { name: '账户菜单' }).click()
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await page.locator('#account').waitFor()
}

;(async () => {
  const browser = await chromium.connectOverCDP(process.env.UI_CDP_URL || 'http://127.0.0.1:19224')
  const page = browser.contexts()[0].pages().find(value => value.url().includes('index.html'))
  assert(page)
  const failures = []
  page.on('pageerror', () => failures.push('renderer error'))
  try {
    if (phase === 'remember') {
      await page.locator('#account').waitFor()
      await page.waitForFunction(() => !document.querySelector('#account').disabled)
      await page.locator('#account').fill('')
      await page.locator('.login-button').click()
      await page.getByRole('status').filter({ hasText: '请输入账号。' }).waitFor()
      await page.locator('#account').fill(username)
      await page.locator('.login-button').click()
      await page.getByRole('status').filter({ hasText: '请输入密码。' }).waitFor()
      await page.locator('#password').fill('intentionally-incorrect-password-for-test')
      await page.getByRole('button', { name: '显示密码', exact: true }).click()
      assert.equal(await page.locator('#password').getAttribute('type'), 'text')
      await page.getByRole('button', { name: '隐藏密码', exact: true }).click()
      await page.locator('.login-button').click()
      await page.getByRole('status').filter({ hasText: '账号或密码错误。' }).waitFor()
      await page.locator('#account').fill('')
      await page.locator('#password').fill('')
      await page.waitForFunction(() => { const video = document.querySelector('video'); return video.readyState >= 2 && video.currentTime > 0.2 })
      await page.getByRole('button', { name: '暂停背景视频' }).click()
      assert.equal(await page.locator('video').evaluate(element => element.paused), true)
      await page.getByRole('button', { name: '播放背景视频' }).click()
      await page.screenshot({ path: path.join(artifacts, 'windows-auth-login.png') })
      await login(page, true)
      await page.screenshot({ path: path.join(artifacts, 'windows-ai-workspace.png') })
    } else if (phase === 'restore') {
      await aiWorkspace(page)
      const logout = await page.evaluate(() => window.desktop.auth.logout())
      assert.equal(logout.ok, true)
      await page.reload()
      await page.locator('#account').waitFor()
      assert.equal(await page.locator('#password').inputValue(), '')
      assert.equal((await page.evaluate(() => window.desktop.auth.current())).data, null)
    } else if (phase === 'normal') {
      await login(page, false)
    } else if (phase === 'design') {
      await page.locator('#account').waitFor()
      await page.waitForFunction(() => !document.querySelector('#account').disabled)
      await page.locator('#account').fill('')
      await page.locator('#password').fill('')
      await page.waitForFunction(() => document.querySelector('video').readyState >= 2)
      await page.screenshot({ path: path.join(artifacts, 'windows-transparent-login.png') })
      await login(page, true)
      const editor = page.locator('#chat-message')
      const send = page.getByRole('button', { name: '发送消息', exact: true })
      assert.equal(await send.isDisabled(), true)
      await editor.fill('帮我查看最近七天的客户变化')
      await editor.press('Shift+Enter')
      assert.equal((await editor.inputValue()).endsWith('\n'), true)
      await editor.fill('帮我查看最近七天的客户变化')
      await editor.press('Enter')
      await page.getByRole('status').filter({ hasText: '请先在控制台添加并启用 AI 连接。' }).waitFor()
      assert.equal(await editor.inputValue(), '帮我查看最近七天的客户变化')
      // IME confirmation must not submit a partially composed Chinese message.
      await editor.fill('测试中文输入')
      await editor.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true })
      assert.equal(await page.getByRole('status').innerText(), '')
      await page.getByRole('button', { name: '新建对话', exact: true }).click()
      assert.equal(await editor.inputValue(), '')
      assert.equal(await editor.evaluate(element => element === document.activeElement), true)
      await page.getByRole('button', { name: '账户菜单' }).click()
      await page.getByRole('button', { name: '退出登录', exact: true }).waitFor()
      await page.keyboard.press('Escape')
      assert.equal(await page.getByRole('button', { name: '账户菜单' }).getAttribute('aria-expanded'), 'false')
      await page.getByRole('button', { name: '账户菜单' }).click()
      await page.getByRole('button', { name: '退出登录', exact: true }).click()
      await page.locator('#account').waitFor()
      await login(page, true)
      await editor.fill('')
      await page.screenshot({ path: path.join(artifacts, 'windows-ai-workspace.png') })
      const bounds = await page.locator('.chat-composer').boundingBox()
      assert(bounds && bounds.width > 300 && bounds.x >= 0)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
    } else if (phase === 'modules') {
      assert(accounts.length >= 2)
      await page.waitForFunction(() => !!document.querySelector('.workspace-page') || !!(document.querySelector('#account') && !document.querySelector('#account').disabled))
      if (await page.locator('.workspace-page').count()) await logout(page)
      await login(page, false, 1)
      assert.equal(await page.locator('.account-label > span').innerText(), '员工')
      const left = page.getByRole('complementary', { name: '模块导航', exact: true })
      const right = page.getByRole('region', { name: 'AI 聊天区域', exact: true })
      assert.equal(await left.getByRole('button', { name: '新建对话', exact: true }).count(), 0)
      assert.equal(await left.getByRole('button', { name: '对话记录', exact: true }).count(), 0)
      assert.equal(await right.getByRole('button', { name: '新建对话', exact: true }).count(), 1)
      await right.getByRole('button', { name: '对话记录', exact: true }).click()
      await page.getByRole('complementary', { name: '对话记录', exact: true }).waitFor()
      await page.getByText('暂无对话记录', { exact: true }).waitFor()
      await page.screenshot({ path: path.join(artifacts, 'windows-dark-history.png') })
      await page.keyboard.press('Escape')
      assert.equal(await page.locator('.history-drawer').count(), 0)
      await page.screenshot({ path: path.join(artifacts, 'windows-dark-employee.png') })
      await page.locator('#chat-message').fill('员工临时草稿：切换账号后应清空')
      await logout(page)
      await login(page, true, 0)
      assert.equal(await page.locator('.account-label > span').innerText(), '管理员')
      assert.equal(await page.locator('#chat-message').inputValue(), '')
      assert.equal(await page.locator('.history-drawer').count(), 0)
      await page.screenshot({ path: path.join(artifacts, 'windows-dark-admin.png') })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
    } else if (phase === 'fresh') {
      await page.locator('#account').waitFor()
      await page.waitForFunction(() => !document.querySelector('#account').disabled)
      assert.equal(await page.locator('#password').inputValue(), '')
      assert.equal((await page.evaluate(() => window.desktop.auth.current())).data, null)
      await page.screenshot({ path: path.join(artifacts, 'windows-auth-final-login.png') })
    } else throw new Error('Unknown test phase')
    assert.deepEqual(failures, [])
    const result = { passed: true, phase, environment: 'Windows Electron -> Arch HTTPS',
      workspace: 'AI', rendererErrors: failures.length }
    fs.writeFileSync(path.join(artifacts, `auth-${phase}.json`), JSON.stringify(result, null, 2))
    console.log(JSON.stringify(result))
  } finally { await browser.close() }
})().catch(() => { console.error(JSON.stringify({ passed: false, phase, message: 'Verification failed; inspect UI without logging credentials.' })); process.exitCode = 1 })
