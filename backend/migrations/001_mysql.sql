CREATE TABLE IF NOT EXISTS repository_locks (name VARCHAR(40) CHARACTER SET ascii PRIMARY KEY) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS roles (code VARCHAR(40) CHARACTER SET ascii PRIMARY KEY, name VARCHAR(100) NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS permissions (code VARCHAR(160) CHARACTER SET ascii PRIMARY KEY) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS role_permissions (
 role_code VARCHAR(40) CHARACTER SET ascii NOT NULL, permission_code VARCHAR(160) CHARACTER SET ascii NOT NULL,
 PRIMARY KEY(role_code,permission_code), FOREIGN KEY(role_code) REFERENCES roles(code), FOREIGN KEY(permission_code) REFERENCES permissions(code)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS users (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY, username VARCHAR(160) COLLATE utf8mb4_bin NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(40) CHARACTER SET ascii NOT NULL,
 workspace_id VARCHAR(100) COLLATE utf8mb4_bin NOT NULL, active BOOLEAN NOT NULL,
 auth_version BIGINT NOT NULL, created_at BIGINT NOT NULL, INDEX(workspace_id), FOREIGN KEY(role) REFERENCES roles(code)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS user_roles (
 user_id CHAR(36) CHARACTER SET ascii NOT NULL, role_code VARCHAR(40) CHARACTER SET ascii NOT NULL,
 PRIMARY KEY(user_id,role_code), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY(role_code) REFERENCES roles(code)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 token_hash CHAR(64) CHARACTER SET ascii PRIMARY KEY, user_id CHAR(36) CHARACTER SET ascii NOT NULL,
 created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL, remember BOOLEAN NOT NULL, auth_version BIGINT NOT NULL,
 INDEX(user_id), INDEX(expires_at), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS login_attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, bucket VARCHAR(100) CHARACTER SET ascii NOT NULL,
 attempt_at BIGINT NOT NULL, INDEX(bucket), INDEX(attempt_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS employees (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY, workspace_id VARCHAR(100) COLLATE utf8mb4_bin NOT NULL,
 user_id CHAR(36) CHARACTER SET ascii NOT NULL UNIQUE,
 name VARCHAR(80) NOT NULL DEFAULT '', avatar TEXT NULL,
 department VARCHAR(100) NOT NULL DEFAULT '', job_title VARCHAR(100) NOT NULL DEFAULT '', phone VARCHAR(32) NOT NULL DEFAULT '',
 employment_status ENUM('active','resigned') NOT NULL DEFAULT 'active',
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 INDEX(workspace_id,employment_status), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
